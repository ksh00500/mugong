import {test,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import {emptyGame,startRun,spawnWave} from '../../src/domain/game';
import {REGIONS} from '../../src/domain/campaign';
import {ART_WEAPONS,maximumHp,xpThreshold} from '../../src/domain/content';
import {makeLootItem} from '../../src/domain/items';
import {techniqueStats} from '../../src/domain/techniques';
import type {ArtId,BoundFighter,Fighter} from '../../src/domain/model';
const root='docs/verification/ingame-capture-20261018';
const styles:ArtId[]=['huashan','tang','wudang','gaebang','shaolin','samja','tianmo','tang','tianmo','jegal'];
const appearances:Fighter['appearance'][]=[0,6,7,2,5,1,4,8,3,9];
for(let region=0;region<REGIONS.length;region++)test(`capture region ${region} ${REGIONS[region].name}`,async({page})=>{
 const errors:string[]=[],failed:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400&&/\/(art|assets|fonts|audio)\//.test(new URL(r.url()).pathname))failed.push(new URL(r.url()).pathname);});
 const state=emptyGame();startRun(state,'무명',20261015+region);const run=state.run!,f=run.fighter as BoundFighter;
 const other=REGIONS.filter((_,i)=>i!==region).slice(0,3);
 run.regionRoute=[other[0].name,other[1].name,REGIONS[region].name,other[2].name];
 f.level=f.spent=run.spent=12;f.xp=xpThreshold(12)+15;f.appearance=appearances[region];f.augments=['swift'];f.augmentOffers=[];
 const primary=styles[region],secondary:ArtId=primary==='samja'?'wudang':'samja';
 const first=makeLootItem(`weapon-${ART_WEAPONS[primary]}-1`,'photo-primary','weapon');
 const second=makeLootItem(`weapon-${ART_WEAPONS[secondary]}-1`,'photo-secondary','weapon');
 first.x=0;first.y=0;second.x=2;second.y=0;
 f.items=[first,second,makeLootItem('medicine-small','photo-medicine','general')];
 f.bindings={[primary]:first.id,[secondary]:second.id};
 f.arts=[{id:primary,level:Math.max(5,techniqueStats(primary,5).ultimateLevel),gauge:100,combo:0,defenseCd:0},{id:secondary,level:3,gauge:0,combo:0,defenseCd:0}];
 f.active=0;run.wave=15;run.gold=72;run.kills=112;spawnWave(run);run.offers=[];
 f.x=960;f.y=440;f.hp=Math.floor(maximumHp(f)*.9);
 await page.goto('/');await expect(page.locator('.home-scene')).toBeVisible({timeout:45000});
 await page.evaluate(async(value)=>{
  const db=await new Promise<IDBDatabase>((resolve,reject)=>{const q=indexedDB.open('mugong-local-v1',1);q.onsuccess=()=>resolve(q.result);q.onerror=()=>reject(q.error);});
  await new Promise<void>((resolve,reject)=>{const tx=db.transaction('saves','readwrite');tx.objectStore('saves').put(value,'current');tx.oncomplete=()=>resolve();tx.onerror=()=>reject(tx.error);});db.close();
 },state);
 await page.reload();await expect(page.locator('.game-canvas')).toHaveAttribute('data-ready','true',{timeout:45000});
 await expect(page.locator('.game-canvas')).toHaveAttribute('data-art-region',String(region));
 await page.evaluate(()=>document.fonts.ready);
 const box=(await page.locator('canvas').first().boundingBox())!;
 await page.mouse.move(box.x+box.width*.5,box.y+box.height*.27);
 await page.keyboard.down('w');await page.waitForTimeout(100);await page.keyboard.up('w');
 await page.mouse.down();await page.waitForTimeout(180);
 await mkdir(root,{recursive:true});const id=String(region).padStart(2,'0');
 await page.screenshot({path:`${root}/${id}-combat.png`,animations:'allow'});await page.mouse.up();
 await page.waitForTimeout(800);
 await expect(page.locator('.ultimate-panel')).toHaveClass(/ultimate-ready/);
 await page.mouse.down({button:'right'});
 await expect(page.locator('.ultimate-panel')).not.toHaveClass(/ultimate-ready/,{timeout:5000});
 await page.mouse.up({button:'right'});
 if(primary==='gaebang') {await page.mouse.down();await page.waitForTimeout(220);await page.mouse.up();}
 else await page.waitForTimeout(100);
 await page.screenshot({path:`${root}/${id}-ultimate.png`,animations:'allow'});
 expect(errors).toEqual([]);expect(failed).toEqual([]);
 await writeFile(`${root}/${id}.json`,JSON.stringify({region,name:REGIONS[region].name,viewport:{width:1920,height:1080},images:[`${id}-combat.png`,`${id}-ultimate.png`],kind:'actual compiled gameplay rendered from independent photography fixture',wave:15,primary,appearance:f.appearance,noArtRecomposition:true,errors,failed,actualUserSaveTouched:false},null,2)+'\n');
});
